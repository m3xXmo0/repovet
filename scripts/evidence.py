"""Generate the "Evidence" section of README.md from measured results.

Usage: python scripts/evidence.py [--write] [--date YYYY-MM-DD]

The section between ``<!-- evidence:start -->`` and ``<!-- evidence:end -->`` is built
from two sources, so its numbers are never typed by hand:

- the reconstructions of documented attacks (``tests/reconstructions/``), scanned
  offline right now with the installed rules;
- the false-positive benchmark data (``docs/fp-benchmark.json``).

Without ``--write`` the section is printed. ``--write`` replaces it in README.md and
stamps it with today's date (or ``--date``). ``tests/test_evidence.py`` regenerates the
section with the date found in README.md and fails if anything else differs.
"""

import argparse
import json
import re
import sys
from collections.abc import Mapping, Sequence
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import fp_benchmark

import reconstructions
from repovet import __version__

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
START = "<!-- evidence:start -->"
END = "<!-- evidence:end -->"
REPO_URL = "https://github.com/m3xXmo0/repovet/blob/main"
STATUSES = ("detected", "partly detected", "not detected")
MOST_FREQUENT = 5
_DATE = re.compile(r"\(repovet [^,]+, (\d{4}-\d{2}-\d{2})\)")


def _rules(expectations: Sequence[reconstructions.Expectation]) -> str:
    return ", ".join(sorted({e.rule for e in expectations})) or "-"


def _gaps(entry: reconstructions.Entry) -> str:
    """Known gaps; with the file when the same rule also fires elsewhere in the entry."""
    firing = {e.rule for e in entry.must_fire}
    labels = {
        f"{gap.rule} in `{gap.path}`" if gap.rule in firing and gap.path else gap.rule
        for gap in entry.known_gaps
    }
    return ", ".join(sorted(labels)) or "-"


def render(
    evaluations: Sequence[reconstructions.Evaluation],
    benchmark: Mapping[str, Any],
    *,
    version: str,
    date: str,
) -> str:
    """The section between the markers (without them)."""
    by_status = {s: sum(e.status == s for e in evaluations) for s in STATUSES}
    head = fp_benchmark.headline(benchmark)
    frequent = fp_benchmark.rule_table(benchmark)[:MOST_FREQUENT]
    scanned = head["scanned"]
    lines = [
        "<!-- Generated by scripts/evidence.py and checked by tests/test_evidence.py. "
        "Do not edit by hand. -->",
        "",
        f"**Detection: reconstructions of documented attacks** (repovet {version}, {date})",
        "",
        f"{len(evaluations)} publicly documented supply-chain incidents and repository "
        "attack techniques are rebuilt as inert files (placeholder hosts, no working "
        "payloads) and scanned on every test run: "
        f"**{by_status['detected']} detected**, "
        f"**{by_status['partly detected']} partly detected** (some expected rules fire, "
        "others are known gaps), "
        f"**{by_status['not detected']} not detected**. Each entry links its public "
        "sources.",
        "",
        "| Technique | Year | Result | Rules that fire | Known gaps |",
        "|-----------|-----:|--------|-----------------|------------|",
    ]
    order = {s: i for i, s in enumerate(STATUSES)}
    for evaluation in sorted(
        evaluations, key=lambda e: (order[e.status], -e.entry.year, e.entry.id)
    ):
        entry = evaluation.entry
        link = f"[{entry.title}]({REPO_URL}/tests/reconstructions/{entry.id}.yaml)"
        lines.append(
            f"| {link} | {entry.year} | {evaluation.status} | {_rules(entry.must_fire)} "
            f"| {_gaps(entry)} |"
        )
    lines += [
        "",
        f"**False positives: the {benchmark['requested']} most-starred GitHub repositories** "
        f"(repovet {benchmark['repovet']}, {benchmark['date']})",
        "",
        f"{scanned} scanned offline with all rules, {head['skipped']} skipped (too large "
        f"to clone or failed; listed in the report). {head['repos_high']} of {scanned} "
        "had at least one high or critical "
        "finding. Findings: "
        + ", ".join(f"{head[s]} {s}" for s in fp_benchmark.SEVERITIES)
        + ". These projects are presumed benign, so every finding is a false positive or "
        "something the project does on purpose.",
    ]
    if frequent:
        lines += [
            "",
            "Rules that fire most often (repositories with a finding): "
            + ", ".join(
                f"{r['rule']} ({r['severity']}, {r['repos']} of {scanned})" for r in frequent
            )
            + ".",
        ]
    lines += [
        "",
        f"Per rule and per repository: [docs/fp-benchmark.md]({REPO_URL}/docs/fp-benchmark.md).",
        "",
        "**No findings does not mean safe.** repovet reports only what its rules detect in "
        "the checked scope; the known gaps above are examples of what it misses.",
    ]
    return "\n".join(lines)


def current_section(text: str) -> str:
    if text.count(START) != 1 or text.count(END) != 1:
        raise ValueError(f"README.md must contain {START} and {END} once each")
    return text.split(START, 1)[1].split(END, 1)[0].strip("\n")


def section_date(section: str) -> str | None:
    """The date of the reconstruction results stamped in a section."""
    match = _DATE.search(section)
    return match.group(1) if match else None


def replace_section(text: str, section: str) -> str:
    before, rest = text.split(START, 1)
    after = rest.split(END, 1)[1]
    return f"{before}{START}\n{section}\n{END}{after}"


def build_section(date: str) -> str:
    evaluations = reconstructions.evaluate_all(reconstructions.load_entries())
    problems = [line for e in evaluations for line in reconstructions.describe(e)]
    if problems:
        raise SystemExit("reconstructions do not match their expectations:\n" + "\n".join(problems))
    benchmark = json.loads(fp_benchmark.DATA.read_text(encoding="utf-8"))
    return render(evaluations, benchmark, version=__version__, date=date)


def run(argv: Sequence[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="update README.md")
    parser.add_argument("--date", help="date of the results (default: today)")
    args = parser.parse_args(argv)
    section = build_section(args.date or datetime.now(UTC).date().isoformat())
    if not args.write:
        print(section)
        return 0
    text = README.read_text(encoding="utf-8")
    current_section(text)  # both markers present
    README.write_text(replace_section(text, section), encoding="utf-8")
    print(f"updated {README}")
    return 0


if __name__ == "__main__":
    sys.exit(run(sys.argv[1:]))
